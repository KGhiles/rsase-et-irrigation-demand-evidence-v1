class ScalarKind(str, Enum):
    """Portable scalar kinds used by the Phase 4 validators."""

    STRING = "string"
    INTEGER = "integer"
    FLOAT = "float"
    BOOLEAN = "boolean"
    DATE = "date"


@dataclass(frozen=True, slots=True)
class ColumnRule:
    """Expected representation and admissible values for one table column."""

    kind: ScalarKind
    nullable: bool = False
    allowed_values: tuple[Any, ...] = ()
    regex: str | None = None
    min_value: float | None = None
    max_value: float | None = None


@dataclass(frozen=True, slots=True)
class TableSchema:
    """Frozen structural contract for a curated CSV input."""

    name: str
    relative_path: str
    expected_rows: int
    exact_columns: tuple[str, ...]
    primary_key: tuple[str, ...]
    column_rules: Mapping[str, ColumnRule] = field(default_factory=dict)
    notes: str = ""

    @property
    def required_columns(self) -> tuple[str, ...]:
        return self.exact_columns

    @property
    def nullable_columns(self) -> tuple[str, ...]:
        return tuple(
            column
            for column, rule in self.column_rules.items()
            if rule.nullable
        )


@dataclass(frozen=True, slots=True)
class JsonSchema:
    """Top-level structure contract for a curated JSON input."""

    name: str
    relative_path: str
    required_top_level_keys: tuple[str, ...]
    exact_top_level_keys: bool = True
    notes: str = ""


@dataclass(frozen=True, slots=True)
class RasterSchema:
    """Frozen metadata contract for a curated raster input."""

    name: str
    relative_path: str
    driver: str
    band_count: int
    band_descriptions: tuple[str, ...]
    crs: str
    pixel_size_x: float
    pixel_size_y: float
    dtype: str
    use_boundary: str


def _frozen_mapping(values: Mapping[str, Any]) -> Mapping[str, Any]:
    """Return a read-only mapping while preserving typed schema objects."""

    return MappingProxyType(dict(values))

