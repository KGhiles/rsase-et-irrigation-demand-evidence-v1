def table_schema(name: str) -> TableSchema:
    """Return a table schema or raise a descriptive ``KeyError``."""

    try:
        return TABLE_SCHEMAS[name]
    except KeyError as exc:
        raise KeyError(f"Unknown Phase 4 table schema: {name!r}") from exc


