"""Frozen table, JSON, and raster schemas for the Phase 4 analytical package.

This module is metadata only. It does not read notebooks, calculate manuscript
results, or import pandas. Runtime validators use these immutable definitions to
check the exclusive Phase 3 input layer before any scientific calculation starts.

Authority boundary
------------------
* Runtime data come only from ``PHASE3_CURATED_INPUT_LAYER_FINAL_002``.
* Historical notebooks remain provenance-only.
* V50 is admissible only for HLS temporal-support and the non-2011
  ``Class I candidate`` row.
* The compact Figure 3 GeoTIFF is for visualization, not full-resolution area
  recomputation.
* Known-cold outputs are sensitivity diagnostics, not corrected or validated ET.
"""

