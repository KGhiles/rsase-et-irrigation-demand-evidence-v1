def schema_for_relative_path(relative_path: str) -> TableSchema | JsonSchema | RasterSchema:
    """Resolve a schema using its Phase 3-relative file path."""

    matches = [
        schema
        for registry in (TABLE_SCHEMAS, JSON_SCHEMAS, RASTER_SCHEMAS)
        for schema in registry.values()
        if schema.relative_path == relative_path
    ]
    if not matches:
        raise KeyError(f"No Phase 4 schema registered for {relative_path!r}")
    if len(matches) != 1:
        raise RuntimeError(f"Duplicate schema registrations for {relative_path!r}")
    return matches[0]


def assert_schema_registry_integrity() -> None:
    """Validate internal metadata consistency without reading runtime data."""

    paths = list(ALL_RUNTIME_PATHS)
    if len(paths) != len(set(paths)):
        raise RuntimeError("Duplicate runtime paths in the Phase 4 schema registry")

    for name, schema in TABLE_SCHEMAS.items():
        if schema.name != name:
            raise RuntimeError(f"Table registry key/name mismatch: {name!r}")
        if not schema.exact_columns:
            raise RuntimeError(f"Table schema has no columns: {name!r}")
        missing_key_columns = set(schema.primary_key) - set(schema.exact_columns)
        if missing_key_columns:
            raise RuntimeError(
                f"Primary-key columns missing from {name!r}: "
                f"{sorted(missing_key_columns)}"
            )
        missing_rules = set(schema.exact_columns) - set(schema.column_rules)
        extra_rules = set(schema.column_rules) - set(schema.exact_columns)
        if missing_rules or extra_rules:
            raise RuntimeError(
                f"Column-rule mismatch for {name!r}; missing={sorted(missing_rules)}, "
                f"extra={sorted(extra_rules)}"
            )

    for registry_name, registry in (
        ("JSON_SCHEMAS", JSON_SCHEMAS),
        ("RASTER_SCHEMAS", RASTER_SCHEMAS),
    ):
        for name, schema in registry.items():
            if schema.name != name:
                raise RuntimeError(
                    f"{registry_name} key/name mismatch: {name!r}"
                )


assert_schema_registry_integrity()
